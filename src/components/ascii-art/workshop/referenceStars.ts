import type { NightStar } from "../NightStars";

type StarPlacement = readonly [
	x: number,
	y: number,
	size: number,
	opacity: number,
];

function toStars(placements: readonly StarPlacement[]): NightStar[] {
	return placements.map(([x, y, size, opacity]) => ({ x, y, size, opacity }));
}

