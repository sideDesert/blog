function drawEastBoulderContact(ctx: CanvasRenderingContext2D) {
	ctx.translate(797, 452);
	ctx.scale(1, 0.16);
	const shade = ctx.createRadialGradient(0, 0, 12, 0, 0, 72);
	shade.addColorStop(0, "#141210a6");
	shade.addColorStop(0.58, "#15120f54");
	shade.addColorStop(1, "#15120f00");
	ctx.fillStyle = shade;
	ctx.fillRect(-72, -72, 144, 144);
}

function drawBoulderFacet(
	ctx: CanvasRenderingContext2D,
	rock: ForegroundBoulder,
	face: string,
	topInk: string,
	bottomInk: string,
) {
	ctx.clip(new Path2D(rock.outline));
	const shade = ctx.createLinearGradient(0, rock.top, 0, rock.bottom);
	shade.addColorStop(0, topInk);
	shade.addColorStop(1, bottomInk);
	fill(ctx, face, shade);
}

