import { fill, fillTerrainContours } from "./canvasShapes";

type ForegroundBoulder = {
	outline: string;
	top: number;
	bottom: number;
	shading: readonly (readonly [tone: number, path: string])[];
};

function drawBoulderBody(
	ctx: CanvasRenderingContext2D,
	{ outline, top, bottom }: ForegroundBoulder,
) {
	const stone = ctx.createLinearGradient(0, top, 0, bottom);
	stone.addColorStop(0, "#393129");
	stone.addColorStop(0.46, "#27221c");
	stone.addColorStop(1, "#141312");
	fill(ctx, outline, stone);
}

function drawBoulderContours(
	ctx: CanvasRenderingContext2D,
	{ outline, shading }: ForegroundBoulder,
) {
	ctx.save();
	ctx.clip(new Path2D(outline));
	fillTerrainContours(ctx, shading);
	ctx.restore();
}

export function drawStratifiedBoulder(
	ctx: CanvasRenderingContext2D,
	boulder: ForegroundBoulder,
) {
	drawBoulderBody(ctx, boulder);
	drawBoulderContours(ctx, boulder);
}

